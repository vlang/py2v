def descending(start: int, stop: int, step: int) -> None:
    for value in range(start, stop, step):
        print(value)


descending(7, -1, -3)
descending(1, 7, -2)
for value in range(0, 8, 3):
    print(value)
for value in range(-2):
    print(value)
for value in range(3 ** 2, 11, 2):
    print(value)
