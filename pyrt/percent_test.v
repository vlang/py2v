fn percent_error_text(template string, operand Value) string {
    percent_format(template, operand) or {
        if e := caught(err, 'BaseException') { return e.class_name + '|' + e.msg() }
        return err.msg()
    }
    return '<no error>'
}

fn test_percent_format_errors() {
    // python: error_text(lambda: '%d' % 'x') == 'TypeError|%d format: a real number is required, not str'
    assert percent_error_text('%d', Value('x')) == 'TypeError|%d format: a real number is required, not str'
    // python: error_text(lambda: '%x' % 1.5) == 'TypeError|%x format: an integer is required, not float'
    assert percent_error_text('%x', Value(f64(1.5))) == 'TypeError|%x format: an integer is required, not float'
    // python: error_text(lambda: '%f' % 'x') == 'TypeError|must be real number, not str'
    assert percent_error_text('%f', Value('x')) == 'TypeError|must be real number, not str'
    // python: error_text(lambda: '%c' % 1.2) == 'TypeError|%c requires int or char'
    assert percent_error_text('%c', Value(f64(1.2))) == 'TypeError|%c requires int or char'
    // python: error_text(lambda: '%c' % 'ab') == 'TypeError|%c requires int or char'
    assert percent_error_text('%c', Value('ab')) == 'TypeError|%c requires int or char'
    // python: error_text(lambda: '%c' % -1) == 'OverflowError|%c arg not in range(0x110000)'
    assert percent_error_text('%c', Value(i64(-1))) == 'OverflowError|%c arg not in range(0x110000)'
    // python: error_text(lambda: '%d' % float('inf')) == 'OverflowError|cannot convert float infinity to integer'
    assert percent_error_text('%d', Value(infinity())) == 'OverflowError|cannot convert float infinity to integer'
    // python: error_text(lambda: '%d' % float('nan')) == 'ValueError|cannot convert float NaN to integer'
    assert percent_error_text('%d', Value(infinity() - infinity())) == 'ValueError|cannot convert float NaN to integer'
    // python: error_text(lambda: '%s %s' % ('x',)) == 'TypeError|not enough arguments for format string'
    assert percent_error_text('%s %s', Value(new_tuple([Value('x')]))) == 'TypeError|not enough arguments for format string'
    // python: error_text(lambda: '%s' % ('x', 'y')) == 'TypeError|not all arguments converted during string formatting'
    assert percent_error_text('%s', Value(new_tuple([Value('x'), Value('y')]))) == 'TypeError|not all arguments converted during string formatting'
    // python: error_text(lambda: '%' % ()) == 'ValueError|incomplete format'
    assert percent_error_text('%', Value(new_tuple([]Value{}))) == 'ValueError|incomplete format'
    // python: error_text(lambda: '%q' % 1) == "ValueError|unsupported format character 'q' (0x71) at index 1"
    assert percent_error_text('%q', Value(i64(1))) == 'ValueError|unsupported format character \'q\' (0x71) at index 1'
    // python: error_text(lambda: '%(key)s' % ()) == 'TypeError|format requires a mapping'
    assert percent_error_text('%(key)s', Value(new_tuple([]Value{}))) == 'TypeError|format requires a mapping'
    // python: error_text(lambda: '%(key)s' % {}) == "KeyError|'key'"
    assert percent_error_text('%(key)s', from_map(map[string]Value{})) == 'KeyError|\'key\''
    // python: error_text(lambda: '%(key' % {}) == 'ValueError|incomplete format key'
    assert percent_error_text('%(key', from_map(map[string]Value{})) == 'ValueError|incomplete format key'
    // python: error_text(lambda: '%*s' % ('x', 'y')) == 'TypeError|* wants int'
    assert percent_error_text('%*s', Value(new_tuple([Value('x'), Value('y')]))) == 'TypeError|* wants int'
    // python: error_text(lambda: 'plain' % 1) == 'TypeError|not all arguments converted during string formatting'
    assert percent_error_text('plain', Value(i64(1))) == 'TypeError|not all arguments converted during string formatting'
    // python: error_text(lambda: '%s' % ()) == 'TypeError|not enough arguments for format string'
    assert percent_error_text('%s', Value(new_tuple([]Value{}))) == 'TypeError|not enough arguments for format string'
    // python: error_text(lambda: '%(x)s %s' % {'x': 1}) == 'TypeError|not enough arguments for format string'
    assert percent_error_text('%(x)s %s', from_map(map[string]Value{'x': Value(i64(1))})) == 'TypeError|not enough arguments for format string'
}
